const BITMAP_ICONS = { lasso: LASSO, bucket: BUCKET, pencil: PENCIL, eraser: ERASER };

// 툴 팔레트 한 칸(26×20) 크기의 아이콘 비트맵
export function toolIcon(name) {
  const cell = new Bitmap(CELL_WIDTH, CELL_HEIGHT);
  const ink = (x, y) => cell.set(x, y, BLACK);
  const gray = (x, y) => cell.set(x, y, patternAt(GRAY, x, y));

  if (BITMAP_ICONS[name]) {
    cell.draw(Bitmap.fromStrings(BITMAP_ICONS[name]), 5, 2);
    return cell;
  }

  switch (name) {
    case 'select':
      shape(4, 4, 21, 15, { kind: 'rect' }, (x, y) => {
        if ((x + y) % 4 < 2) ink(x, y);
      });
      break;
    case 'line':
      line(5, 4, 20, 15, ink);
      break;
    case 'rect':
    case 'rectFill':
      shape(4, 4, 21, 15, { kind: 'rect' }, ink, name.endsWith('Fill') ? gray : null);
      break;
    case 'rrect':
    case 'rrectFill':
      shape(4, 4, 21, 15, { kind: 'rrect', radius: 4 }, ink, name.endsWith('Fill') ? gray : null);
      break;
    case 'oval':
    case 'ovalFill':
      shape(4, 4, 21, 15, { kind: 'oval' }, ink, name.endsWith('Fill') ? gray : null);
      break;
  }
  return cell;
}
