// 패턴은 문서 좌표에 정렬된다: 어디서 칠하든 무늬가 이어진다.
export function patternAt(rows, x, y) {
  return (rows[y & 7] >> (7 - (x & 7))) & 1;
}

// CSS 배경으로 쓸 수 있는 8×8 PNG data URL
export function patternDataURL(rows) {
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = 8;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, 8, 8);
  ctx.fillStyle = '#000';
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      if (patternAt(rows, x, y)) ctx.fillRect(x, y, 1, 1);
    }
  }
  return canvas.toDataURL();
}
